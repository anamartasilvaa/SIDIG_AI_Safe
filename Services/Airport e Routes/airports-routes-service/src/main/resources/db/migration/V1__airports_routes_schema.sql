-- Airports & Routes Service - esquema inicial (Entrega 2).
-- Gerido pelo Flyway (o Hibernate nao altera o esquema: spring.jpa.hibernate.ddl-auto=none).
-- SQL compativel com PostgreSQL (Modo B) e H2 (Modo A e testes).

-- ===================== Modelo de escrita (agregados) =====================

CREATE TABLE airport (
    pk                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             BIGINT,
    iata_code           VARCHAR(3)   NOT NULL,
    name                VARCHAR(255) NOT NULL,
    city                VARCHAR(255) NOT NULL,
    country             VARCHAR(255) NOT NULL,
    timezone            VARCHAR(255) NOT NULL,
    type                VARCHAR(30)  NOT NULL,
    status              VARCHAR(30)  NOT NULL,
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    image_url           TEXT,
    operational_hours   VARCHAR(255),
    contact_information VARCHAR(255),
    last_modified       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    origin_node_id      VARCHAR(255) NOT NULL,
    CONSTRAINT uk_airport_iata_code UNIQUE (iata_code)
);

CREATE TABLE runway (
    pk          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)     NOT NULL,
    length      DOUBLE PRECISION NOT NULL,
    orientation VARCHAR(255)     NOT NULL,
    airport_pk  BIGINT,
    CONSTRAINT fk_runway_airport FOREIGN KEY (airport_pk) REFERENCES airport (pk)
);

CREATE TABLE airport_facilities (
    airport_pk  BIGINT NOT NULL,
    type        VARCHAR(255),
    description VARCHAR(255),
    CONSTRAINT fk_facility_airport FOREIGN KEY (airport_pk) REFERENCES airport (pk)
);

CREATE TABLE route (
    pk                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               BIGINT,
    route_id              VARCHAR(255) NOT NULL,
    origin_pk             BIGINT       NOT NULL,
    destination_pk        BIGINT       NOT NULL,
    estimated_flight_time INTEGER,
    minimum_range         DOUBLE PRECISION,
    minimum_capacity      INTEGER,
    status                VARCHAR(30)  NOT NULL,
    last_modified         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    origin_node_id        VARCHAR(255) NOT NULL,
    CONSTRAINT uk_route_route_id UNIQUE (route_id),
    CONSTRAINT fk_route_origin FOREIGN KEY (origin_pk) REFERENCES airport (pk),
    CONSTRAINT fk_route_destination FOREIGN KEY (destination_pk) REFERENCES airport (pk)
);

CREATE TABLE route_history (
    pk         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id   VARCHAR(255) NOT NULL,
    action     VARCHAR(255) NOT NULL,
    start_date TIMESTAMP(6) NOT NULL,
    end_date   TIMESTAMP(6)
);
CREATE INDEX ix_route_history_route_id ON route_history (route_id);

-- ===================== Mensagens: outbox e inbox =====================

CREATE TABLE replication_task (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peer_url        VARCHAR(255) NOT NULL,
    http_method     VARCHAR(255) NOT NULL,
    path            VARCHAR(255) NOT NULL,
    payload         TEXT,
    original_user   VARCHAR(255) NOT NULL,
    attempts        INTEGER      NOT NULL,
    status          VARCHAR(30)  NOT NULL,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_modified   TIMESTAMP(6) WITH TIME ZONE,
    origin_node_id  VARCHAR(255)
);
CREATE INDEX ix_replication_task_pending ON replication_task (status, next_attempt_at);

CREATE TABLE processed_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer     VARCHAR(100) NOT NULL,
    event_id     VARCHAR(200) NOT NULL,
    event_type   VARCHAR(50),
    processed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_processed_event UNIQUE (consumer, event_id)
);

-- ===================== CQRS: modelo de leitura =====================

CREATE TABLE airport_read_model (
    iata_code      VARCHAR(255) PRIMARY KEY,
    name           VARCHAR(255),
    city           VARCHAR(255),
    country        VARCHAR(255),
    status         VARCHAR(255),
    last_modified  TIMESTAMP(6) WITH TIME ZONE,
    origin_node_id VARCHAR(255),
    view_json      TEXT NOT NULL
);

CREATE TABLE route_read_model (
    route_id              VARCHAR(255) PRIMARY KEY,
    origin_iata           VARCHAR(255),
    destination_iata      VARCHAR(255),
    status                VARCHAR(255),
    minimum_capacity      INTEGER,
    minimum_range         DOUBLE PRECISION,
    estimated_flight_time INTEGER,
    last_modified         TIMESTAMP(6) WITH TIME ZONE,
    origin_node_id        VARCHAR(255),
    origin_latitude       DOUBLE PRECISION,
    origin_longitude      DOUBLE PRECISION,
    destination_latitude  DOUBLE PRECISION,
    destination_longitude DOUBLE PRECISION
);
CREATE INDEX ix_route_read_model_origin ON route_read_model (origin_iata, status);
CREATE INDEX ix_route_read_model_destination ON route_read_model (destination_iata);
