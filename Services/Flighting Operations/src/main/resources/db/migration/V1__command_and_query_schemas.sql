

CREATE TABLE fo_command.scheduled_flight (
                                             pk                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             version                    BIGINT,
                                             flight_id                  VARCHAR(36)  NOT NULL UNIQUE,
                                             route_id                   VARCHAR(40)  NOT NULL,
                                             aircraft_registration      VARCHAR(20)  NOT NULL,
                                             scheduled_date_time        TIMESTAMP    NOT NULL,
                                             actual_departure_date_time TIMESTAMP,
                                             actual_arrival_date_time   TIMESTAMP,
                                             status                     VARCHAR(20)  NOT NULL,
                                             status_reason              VARCHAR(200),
                                             revision                   BIGINT       NOT NULL,
                                             last_modified_at           TIMESTAMP WITH TIME ZONE NOT NULL,
                                             created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
                                             origin_instance            VARCHAR(60)  NOT NULL
);
CREATE INDEX ix_flight_aircraft_time ON fo_command.scheduled_flight (aircraft_registration, scheduled_date_time);

CREATE TABLE fo_command.aircraft_ref (
                                         registration_number VARCHAR(20) PRIMARY KEY,
                                         model_code          VARCHAR(40),
                                         status              VARCHAR(30) NOT NULL,
                                         maximum_range       DOUBLE PRECISION,
                                         seating_capacity    INTEGER,
                                         revision            BIGINT      NOT NULL,
                                         updated_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE fo_command.route_ref (
                                      route_id         VARCHAR(40) PRIMARY KEY,
                                      origin           VARCHAR(10),
                                      destination      VARCHAR(10),
                                      active           BOOLEAN     NOT NULL,
                                      distance         DOUBLE PRECISION,
                                      minimum_capacity INTEGER,
                                      revision         BIGINT      NOT NULL,
                                      updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE fo_command.outbox_event (
                                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         event_id       VARCHAR(36)    NOT NULL UNIQUE,
                                         exchange_name  VARCHAR(100)   NOT NULL,
                                         routing_key    VARCHAR(100)   NOT NULL,
                                         event_type     VARCHAR(60)    NOT NULL,
                                         aggregate_id   VARCHAR(60)    NOT NULL,
                                         correlation_id VARCHAR(100),
                                         payload        VARCHAR(100000) NOT NULL,
                                         created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
                                         sent_at        TIMESTAMP WITH TIME ZONE,
                                         attempts       INTEGER        NOT NULL,
                                         last_error     VARCHAR(500)
);
CREATE INDEX ix_outbox_pending ON fo_command.outbox_event (sent_at, id);

CREATE TABLE fo_command.processed_event (
                                            consumer     VARCHAR(60) NOT NULL,
                                            event_id     VARCHAR(36) NOT NULL,
                                            processed_at TIMESTAMP WITH TIME ZONE NOT NULL,
                                            PRIMARY KEY (consumer, event_id)
);

CREATE TABLE fo_query.flight_view (
                                      flight_id             VARCHAR(36) PRIMARY KEY,
                                      route_id              VARCHAR(40) NOT NULL,
                                      origin                VARCHAR(10),
                                      destination           VARCHAR(10),
                                      registration_number   VARCHAR(20) NOT NULL,
                                      scheduled_date_time   TIMESTAMP   NOT NULL,
                                      actual_departure      TIMESTAMP,
                                      actual_arrival        TIMESTAMP,
                                      status                VARCHAR(20) NOT NULL,
                                      status_reason         VARCHAR(200),
                                      revision              BIGINT      NOT NULL,
                                      last_modified_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_view_aircraft ON fo_query.flight_view (registration_number, scheduled_date_time);
CREATE INDEX ix_view_route ON fo_query.flight_view (route_id);

CREATE TABLE fo_query.route_utilization_view (
                                                 route_id     VARCHAR(40) PRIMARY KEY,
                                                 origin       VARCHAR(10),
                                                 destination  VARCHAR(10),
                                                 flight_count BIGINT NOT NULL
);
